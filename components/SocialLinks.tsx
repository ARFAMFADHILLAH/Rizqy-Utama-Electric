function Glyph({
  d,
  viewBox = "0 0 24 24",
  evenOdd = false,
}: {
  d: string;
  viewBox?: string;
  evenOdd?: boolean;
}) {
  return (
    <svg viewBox={viewBox} fill="currentColor" aria-hidden="true" className="h-5 w-5">
      <path d={d} fillRule={evenOdd ? "evenodd" : undefined} clipRule={evenOdd ? "evenodd" : undefined} />
    </svg>
  );
}

function Icon({ link }: { link: SocialLink }) {
  switch (link.key) {
    case "instagram":
      return <Glyph d={INSTAGRAM_PATH} />;
    case "linkedin":
      return <Glyph d={LINKEDIN_PATH} />;
    case "shopee":
      return <Glyph d={SHOPEE_PATH} />;
    case "tiktok":
      return <Glyph d={TIKTOK_PATH} />;
    case "tokopedia":
      return <Glyph d={TOKOPEDIA_PATH} viewBox="0 0 1024 1024" evenOdd />;
    case "blibli":
      return <Glyph d={BLIBLI_PATH} />;
  }
}

type Props = {
  variant?: "footer" | "header";
};

export default function SocialLinks({ variant = "footer" }: Props) {
  const links = socialLinks();
  const header = variant === "header";

  return (
    <ul className={header ? "flex items-center gap-0.5" : "flex flex-wrap items-center gap-2"}>
      {links.map((link) => {
        const isPlaceholder = link.href === "#";
        const className = header
          ? "grid h-9 w-9 place-items-center rounded-md text-navy-700 transition hover:bg-gray-100 hover:text-brand-600"
          : "flex items-center gap-2 rounded-md border border-white/15 px-3 py-1.5 text-xs font-medium text-navy-100 transition hover:border-brand-400 hover:text-white";

        const content = (
          <>
            <Icon link={link} />
            {!header && <span>{link.label}</span>}
          </>
        );

        return (
          <li key={link.key}>
            {isPlaceholder ? (
              <span
                aria-disabled="true"
                title={`${link.label} — segera`}
                className={`${className} cursor-default opacity-60`}
              >
                {content}
              </span>
            ) : (
              <a
                href={link.href}
                target="_blank"
                rel="noopener noreferrer"
                aria-label={link.label}
                title={link.label}
                className={className}
              >
                {content}
              </a>
            )}
          </li>
        );
      })}
    </ul>
  );
}
